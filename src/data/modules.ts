const pdfAssets = import.meta.glob<string>("/src/assets/teaching-modules/*.pdf", {
  eager: true,
  query: "?url",
  import: "default",
});

const coverAssets = import.meta.glob<string>("/src/assets/teaching-modules/covers/*.{jpg,png}", {
  eager: true,
  query: "?url",
  import: "default",
});

function pdf(filename: string): string {
  const url = pdfAssets[`/src/assets/teaching-modules/${filename}`];
  if (!url) throw new Error(`Missing teaching module PDF asset: ${filename}`);
  return url;
}

function cover(filename: string): string {
  const url = coverAssets[`/src/assets/teaching-modules/covers/${filename}`];
  if (!url) throw new Error(`Missing teaching module cover asset: ${filename}`);
  return url;
}

